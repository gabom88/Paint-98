const cache = {};
export function icon(name, scale = 1) {
  const key = name + "@" + scale;
  if (cache[key]) return cache[key];
  const rows = I[name].trim().split("\n");
  const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  const c = document.createElement("canvas");
  c.width = w * scale; c.height = h * scale;
  const ctx = c.getContext("2d");
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const col = PAL[row[x]];
      if (col) { ctx.fillStyle = col; ctx.fillRect(x * scale, y * scale, scale, scale); }
    }
  });
  return (cache[key] = c.toDataURL());
}
export function iconImg(name, cls = "") {
  return `<img class="px ${cls}" src="${icon(name)}" alt="" draggable="false">`;
}
